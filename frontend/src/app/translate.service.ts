@Injectable({ providedIn: 'root' })
export class TranslateService {
  private currentLanguage$ = new BehaviorSubject<Language>('en');
  language$: Observable<Language> = this.currentLanguage$.asObservable();

  setLanguage(lang: Language): void {
    this.currentLanguage$.next(lang);
    localStorage.setItem('erp_lang', lang);
  }

  getCurrentLanguage(): Language {
    return this.currentLanguage$.value;
  }

  /** Translate a key for the current language. Falls back to English if not found. */
  translate(key: string): string {
    const lang = this.currentLanguage$.value;
    return TRANSLATIONS[lang][key] ?? TRANSLATIONS['en'][key] ?? key;
  }

  /** Shorthand alias */
  t(key: string): string {
    return this.translate(key);
  }

  init(): void {
    const saved = localStorage.getItem('erp_lang') as Language | null;
    if (saved && ['en', 'mr', 'hi'].includes(saved)) {
      this.currentLanguage$.next(saved);
    }
  }
}

@Pipe({
  name: 'translate',
  pure: true,
  standalone: true
})
export class TranslatePipe implements PipeTransform {
  constructor(private translateService: TranslateService) {}
  transform(key: string, lang: Language): string {
    return this.translateService.translate(key);
  }
}

